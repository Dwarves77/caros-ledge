// Generator pins (IMP-037, IMP-054): the four SQL generators in src/core/contracts and the host_verdicts class CHECK (scripts/gen/host-class-check.mjs) must reproduce what the schema applied. A unit test pins their text to
// a hash; this checks them against the live catalog, so a change to the tier table or the licence register that the applied constraints do not
// follow fails the schema job. Run by scripts/ci/schema-apply.mjs after the migrations (through tests/_support/register.mjs, which resolves "@/").
//   renderTierConstraintsSql    -> emission_factors CHECK constraints, compared by name and by pg_get_constraintdef (the planner's own
//                                  normal form, so formatting cannot differ)
//   renderEnvelopeColumnsSql    -> emission_factors column types, NOT NULL and column CHECKs, same comparison
//   renderFactorCandidateViewSql-> emission_factor_candidates, compared by pg_get_viewdef
//   renderDataSourceSeedSql     -> executes against data_sources (rolled back), is idempotent, and lands every register key with its verdict
//   renderHostClassCheck        -> the host_verdicts class CHECK (migration 0042): the class names of the tier contract, compared with the applied constraint by pg_get_constraintdef (IMP-054)
// Everything runs in a transaction that rolls back. Each comparison is attacked on every run: a mutated copy of the generated text must be
// flagged, or the run fails. Exit 1 on a mismatch or a failed attack; exit 2 when DATABASE_URL is not set.
import { renderHostClassCheck } from "../../gen/host-class-check.mjs";
import { psql } from "../psql.mjs";

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("generator-pins: DATABASE_URL is not set (skipped)");
  process.exit(2);
}
const c = await import("@/core/contracts");

function sql(text) {
  const r = psql(url, { sql: `BEGIN;\n${text}\nROLLBACK;\n`, tuples: true, sep: "\t" });
  if (r.status !== 0) throw new Error(`generator-pins: SQL failed\n${r.stderr}`);
  return r.stdout.split("\n").filter(Boolean).map((l) => l.split("\t"));
}
const noComments = (text) => text.split("\n").filter((l) => !/^\s*--/.test(l)).join("\n");
const AS_APPLIED = "public.emission_factors";

/** Constraints generated by renderTierConstraintsSql vs those on emission_factors. */
function tierMismatches(text) {
  const parts = noComments(text).split(/,\n(?=\s*CONSTRAINT )/).map((p) => p.trim());
  const names = parts.map((p) => /^CONSTRAINT (\w+) /.exec(p)?.[1]);
  if (names.some((n) => !n)) return ["a generated constraint has no name"];
  const rows = sql(`
CREATE TABLE public.pin_ef (LIKE ${AS_APPLIED});
ALTER TABLE public.pin_ef ${parts.map((p) => `ADD ${p}`).join(",\n  ")};
SELECT g.conname, g.def, coalesce(a.def, '(absent)') FROM
  (SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = 'public.pin_ef'::regclass AND contype = 'c') g
  LEFT JOIN (SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = '${AS_APPLIED}'::regclass AND contype = 'c') a USING (conname)
 ORDER BY 1;`);
  const bad = rows.filter(([, g, a]) => g !== a).map(([n, g, a]) => `${n}: generated ${g} / applied ${a}`);
  for (const n of names) if (!rows.some(([r]) => r === n)) bad.push(`${n}: not created`);
  return bad;
}

/** Columns generated by renderEnvelopeColumnsSql vs emission_factors: type, NOT NULL and the column's CHECK. */
function envelopeMismatches(text) {
  const cols = noComments(text).trim().replace(/,$/, "");
  const rows = sql(`
CREATE TABLE public.pin_env (${cols});
SELECT g.attname, g.ty, g.nn, coalesce(g.def, ''), coalesce(a.ty, '(absent)'), coalesce(a.nn, ''), coalesce(a.def, '') FROM
  (SELECT att.attname, format_type(att.atttypid, att.atttypmod) AS ty, att.attnotnull::text AS nn, (SELECT string_agg(pg_get_constraintdef(k.oid), ' ' ORDER BY k.conname) FROM pg_constraint k WHERE k.conrelid = att.attrelid AND k.contype = 'c' AND k.conkey = ARRAY[att.attnum]) AS def
     FROM pg_attribute att WHERE att.attrelid = 'public.pin_env'::regclass AND att.attnum > 0 AND NOT att.attisdropped) g
  LEFT JOIN (SELECT att.attname, format_type(att.atttypid, att.atttypmod) AS ty, att.attnotnull::text AS nn, (SELECT string_agg(pg_get_constraintdef(k.oid), ' ' ORDER BY k.conname) FROM pg_constraint k WHERE k.conrelid = att.attrelid AND k.contype = 'c' AND k.conkey = ARRAY[att.attnum]) AS def
     FROM pg_attribute att WHERE att.attrelid = '${AS_APPLIED}'::regclass AND att.attnum > 0 AND NOT att.attisdropped) a USING (attname)
 ORDER BY 1;`);
  return rows.filter(([, gt, gn, gd, at, an, ad]) => gt !== at || gn !== an || gd !== ad).map(([n, gt, gn, gd, at, an, ad]) => `${n}: generated ${gt} notnull=${gn} ${gd} / applied ${at} notnull=${an} ${ad}`);
}

/** The view generated by renderFactorCandidateViewSql vs emission_factor_candidates. */
function viewMismatches(text) {
  const create = noComments(text).replace("public.emission_factor_candidates", "public.pin_efc");
  if (!create.includes("public.pin_efc")) return ["the generated view is not named public.emission_factor_candidates"];
  const rows = sql(`${create}\nSELECT pg_get_viewdef('public.pin_efc'::regclass, true) = pg_get_viewdef('public.emission_factor_candidates'::regclass, true);`);
  return rows.length === 1 && rows[0]?.[0] === "t" ? [] : ["generated view definition differs from the applied one"];
}

/** The seed generated by renderDataSourceSeedSql: it executes, a second run changes nothing, and every register key lands with its redistribution verdict. */
function seedMismatches(text) {
  const keys = c.SOURCE_KEYS;
  const rows = sql(`
${text}
SELECT count(*)::text, 'first' FROM public.data_sources WHERE source_key = ANY (ARRAY[${keys.map((k) => `'${k}'`).join(",")}]);
${text}
SELECT count(*)::text, 'second' FROM public.data_sources WHERE source_key = ANY (ARRAY[${keys.map((k) => `'${k}'`).join(",")}]);
SELECT source_key, redistribution FROM public.data_sources WHERE source_key = ANY (ARRAY[${keys.map((k) => `'${k}'`).join(",")}]) ORDER BY 1;`);
  const bad = [];
  for (const [n, which] of rows.filter((r) => r[1] === "first" || r[1] === "second")) if (Number(n) !== keys.length) bad.push(`${which} run left ${n} of ${keys.length} register rows`);
  const landed = new Map(rows.filter((r) => r[1] !== "first" && r[1] !== "second").map(([k, v]) => [k, v]));
  for (const k of keys) if (landed.get(k) !== c.SOURCE_LICENCES[k]?.redistribution) bad.push(`${k}: landed ${landed.get(k)}, register says ${c.SOURCE_LICENCES[k]?.redistribution}`);
  return bad;
}

/** The class CHECK generated from the tier contract's class names vs the one applied to host_verdicts. */
function hostClassMismatches(text) {
  const rows = sql(`
CREATE TABLE public.pin_hv (class text, ${text});
SELECT g.def, coalesce(a.def, '(absent)') FROM
  (SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = 'public.pin_hv'::regclass AND contype = 'c') g
  LEFT JOIN (SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = 'public.host_verdicts'::regclass AND conname = 'host_verdicts_class_check') a ON true;`);
  return rows.filter(([g, a]) => g !== a).map(([g, a]) => `generated ${g} / applied ${a}`);
}

const mutate = (text, from, to) => {
  if (!text.includes(from)) throw new Error(`generator-pins: cannot plant a violation, ${JSON.stringify(from)} not in the generated text`);
  return text.replace(from, to);
};
const pins = [
  { name: "renderTierConstraintsSql", text: c.renderTierConstraintsSql(), run: tierMismatches, plant: (t) => mutate(t, "pedigree >= 2", "pedigree >= 1") },
  { name: "renderEnvelopeColumnsSql", text: c.renderEnvelopeColumnsSql(), run: envelopeMismatches, plant: (t) => mutate(t, "BETWEEN 1 AND 5", "BETWEEN 0 AND 5") },
  { name: "renderFactorCandidateViewSql", text: c.renderFactorCandidateViewSql(), run: viewMismatches, plant: (t) => mutate(t, "THEN 1", "THEN 9") },
  { name: "renderDataSourceSeedSql", text: c.renderDataSourceSeedSql(), run: seedMismatches, plant: (t) => mutate(t, "'permitted'", "'prohibited'") },
  { name: "renderHostClassCheck", text: renderHostClassCheck(), run: hostClassMismatches, plant: (t) => mutate(t, "'legal'", "'legal', 'invented'") },
];

let failed = false;
for (const p of pins) {
  const bad = p.run(p.text);
  if (bad.length) {
    failed = true;
    console.error(`FAIL generator-pins ${p.name}: ${bad.length} mismatch(es)`);
    for (const b of bad.slice(0, 10)) console.error(`  ${b}`);
  } else console.log(`PASS generator-pins ${p.name}: the output equals what the schema applied`);
  let planted;
  try {
    planted = p.run(p.plant(p.text));
  } catch (e) {
    planted = [String(e instanceof Error ? e.message : e).split("\n")[0]]; // a planted violation the database refuses outright is also flagged
  }
  if (planted.length) console.log(`  attack flagged: ${planted[0].slice(0, 140)}`);
  if (planted.length === 0) {
    failed = true;
    console.error(`ATTACK FAILED generator-pins ${p.name}: the planted violation passed`);
  }
}
console.log(`generator-pins: ${pins.length} generators checked, ${pins.length} planted violations flagged`);
process.exit(failed ? 1 : 0);
