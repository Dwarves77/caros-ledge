// Generates supabase/migrations/0071_live_check_production_shape.sql: the function public.live_check_production_shape() whose body is scripts/ci/data/production-shape.sql (the query that reads a database's roles, role settings, ACLs and
// platform default privileges as one jsonb document). The live check calls it on the deployed project and compares the answer with the "shape" key of scripts/ci/data/production-shape.json; the schema job calls it on the CI database
// and compares the same way. The migration is GENERATED so that the query the file is read with, the query the CI database answers and the query production answers are one text; `checkShapeFunction` (run by migration-checks)
// fails when the committed migration is not what this renders.
//   node scripts/gen/shape-function-sql.mjs            writes the migration
import { readFileSync, writeFileSync } from "node:fs";

import { isMain } from "../lib/fs.mjs";

export const MIGRATION = "supabase/migrations/0071_live_check_production_shape.sql";
const QUERY_FILE = "scripts/ci/data/production-shape.sql";

/** The shape query as a function body: its leading comment lines and the trailing column alias removed. */
export function queryBody(sql = readFileSync(QUERY_FILE, "utf8").replace(/\r\n/g, "\n")) {
  const body = sql.split("\n").filter((l) => !l.startsWith("--")).join("\n").trim();
  if (!/\) AS shape$/.test(body)) throw new Error(`${QUERY_FILE} no longer ends in \`) AS shape\``);
  return body.replace(/\) AS shape$/, ")");
}

export function renderShapeFunction() {
  return `-- 0071 live_check_production_shape (R1b, remediation G11; good-enough audit K:17, K:18): the shape of the database (roles, memberships, role settings, schema ACLs, default privileges, auth.users and the auth functions) as ONE jsonb document.
--
-- The CI database is built to match scripts/ci/data/production-shape.json (read from production with the query below by scripts/cutover/read-production-shape.mjs). This function is that query, so the live check
-- (scripts/ci/live/checks.mjs, check \`production-shape\`) asks the deployed project the question the file was made from, and the schema job asks the CI database the same: the file, CI and production cannot disagree unseen.
-- It reads the catalog only and returns configuration (role names and attributes, ACL text), never data. Security definer so it sees pg_db_role_setting and information_schema for auth; executable by service_role only.
--
-- GENERATED by scripts/gen/shape-function-sql.mjs from ${QUERY_FILE}. Do not edit by hand: migration-checks fails when this file differs from the generator.
--
-- Reversal: supabase/migrations/down/0071.sql.

-- catalog: function

BEGIN;

CREATE FUNCTION public.live_check_production_shape() RETURNS jsonb
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
    AS $shape$
${queryBody()}
$shape$;
REVOKE ALL ON FUNCTION public.live_check_production_shape() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.live_check_production_shape() TO service_role;
COMMENT ON FUNCTION public.live_check_production_shape() IS 'The shape of the database (roles, role settings, ACLs, default privileges) as one jsonb document; compared with scripts/ci/data/production-shape.json by the live check and the schema job (R1b migration 0071).';

-- Self-check 0071-production-shape: only service_role may execute it (anon and authenticated are refused by the privilege, not by an error inside it); it answers every section the live check compares, the roles it lists include
-- service_role with BYPASSRLS (the attribute the old CI stub lacked), and the answer names the database owner.
DO $$
DECLARE doc jsonb;
BEGIN
  IF has_function_privilege('anon', 'public.live_check_production_shape()', 'EXECUTE') OR has_function_privilege('authenticated', 'public.live_check_production_shape()', 'EXECUTE') THEN
    RAISE EXCEPTION '0071-production-shape: a client role can execute it';
  END IF;
  IF NOT has_function_privilege('service_role', 'public.live_check_production_shape()', 'EXECUTE') THEN RAISE EXCEPTION '0071-production-shape: service_role cannot execute it'; END IF;
  BEGIN
    SET LOCAL ROLE authenticated;
    PERFORM public.live_check_production_shape();
    RESET ROLE;
    RAISE EXCEPTION '0071-production-shape: authenticated executed it';
  EXCEPTION WHEN SQLSTATE '42501' THEN RESET ROLE;
  END;
  doc := public.live_check_production_shape();
  IF NOT (doc ?& ARRAY['databaseOwner', 'roles', 'memberships', 'roleSettings', 'schemaAcls', 'defaultAcls', 'authUsers', 'authFunctions', 'serverSettings']) THEN
    RAISE EXCEPTION '0071-production-shape: the answer lacks a section: %', (SELECT string_agg(k, ',') FROM jsonb_object_keys(doc) k);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements(doc->'roles') r WHERE r->>'name' = 'service_role' AND (r->>'bypassrls')::boolean) THEN RAISE EXCEPTION '0071-production-shape: service_role is not listed with BYPASSRLS'; END IF;
  IF coalesce(doc->>'databaseOwner', '') = '' THEN RAISE EXCEPTION '0071-production-shape: no database owner'; END IF;
  RAISE NOTICE '0071-production-shape OK';
END $$;

COMMIT;
`;
}

/** The problems of the committed migration against the generator (empty when it is exactly what renders). */
export function checkShapeFunction(text) {
  return text.replace(/\r\n/g, "\n") === renderShapeFunction() ? [] : [`${MIGRATION} differs from \`node scripts/gen/shape-function-sql.mjs\` (the migration is generated from ${QUERY_FILE}): regenerate and commit it`];
}

if (isMain(import.meta.url)) writeFileSync(MIGRATION, renderShapeFunction());
