// Generates the cutover-window data migration supabase/migrations/0016_data_source_type_backfill.sql (NOT committed until then): the sources.source_role / source_type backfill, as the
// statements P2-03's renderBackfillSql renders for a plan built with the rules of src/core/sources/classify.ts. It classifies only
// rows whose column is NULL (IMP-032: classify NULL rows once, never overwrite) and every statement is guarded again in SQL.
// The real file is generated at the cutover window from a read-only export of the live registry (the executor's step) and committed then as
// 0016; the schema job proves this generator every run on scripts/ci/fixtures/sources-export-sample.json without committing that output.
// Input: a read-only JSON export of the registry, an array of {id, name, url, source_role, source_type}. Usage:
//   node --import ./tests/_support/register.mjs scripts/gen/source-backfill-sql.mjs <sources-export.json> [label] > supabase/migrations/0016_data_source_type_backfill.sql
import { readFileSync } from "node:fs";

import { classifySourceRole, classifySourceType } from "@/core/sources/classify";
import { renderBackfillSql } from "@/features/sources/classify-sources";

const [file, label = file] = process.argv.slice(2);
if (!file) {
  console.error("usage: node --import ./tests/_support/register.mjs scripts/gen/source-backfill-sql.mjs <sources-export.json> [label]");
  process.exit(2);
}
const sources = JSON.parse(readFileSync(file, "utf8"));
if (!Array.isArray(sources)) throw new Error("the export must be a JSON array");
const plan = [];
for (const s of [...sources].sort((a, b) => String(a.id).localeCompare(String(b.id)))) {
  const entry = { id: s.id };
  const role = s.source_role == null ? classifySourceRole(s.name, s.url) : null;
  if (role) Object.assign(entry, { source_role: role, from_role: null });
  const types = s.source_type == null ? classifySourceType({ name: s.name, url: s.url }) : [];
  if (types.length) entry.source_type = types;
  if (entry.source_role || entry.source_type) plan.push(entry);
}
const roles = plan.filter((p) => p.source_role);
const types = plan.filter((p) => p.source_type);
const ids = (list) => `ARRAY[${list.map((p) => `'${p.id}'`).join(", ")}]::text[]`;

process.stdout.write(`-- 0016 DATA migration: sources.source_role and sources.source_type backfilled once for NULL rows (P2-S2, owed by register P1-06
-- sources-b.md section 8 (backfill-source-type.mjs as a data migration) and IMPROVEMENTS IMP-032).
--
-- GENERATED by scripts/gen/source-backfill-sql.mjs from ${label} (${sources.length} registry rows read, ${plan.length} planned: ${roles.length} source_role, ${types.length} source_type).
-- Do not edit by hand: regenerate from a fresh read-only export of the registry at the cutover window, so the plan matches the rows then live.
--
-- THIS IS A DATA MIGRATION. TWO-TRACK POLICY: it ships with its consumer (src/core/sources/classify.ts, the rules that built the plan) and
-- is RUN ONLY AT THE CUTOVER WINDOW, by the operator's executor; the CI schema job runs it inside a rolled-back transaction after the
-- fixture named below (rule 15), never for real.
--
-- Never overwrites: a source_role update applies only where source_role IS NULL, a source_type update only where source_type IS NULL, by id.
-- A second run changes nothing. An id that no longer exists matches no row.
-- Reversal: UPDATE public.sources SET <column> = NULL for the planned ids returns them to unclassified.

-- catalog: none (data migration, not run by the schema job)
-- rollback-test: scripts/ci/fixtures/data-0016-sources.sql

BEGIN;

CREATE TEMP TABLE _sb_prior ON COMMIT DROP AS
SELECT id, source_role, source_type FROM public.sources WHERE id::text = ANY (${ids(plan)});

${renderBackfillSql(plan)}

-- Self-check 0016-data-source-type: no planned id that exists is left NULL in the column the plan names, and no value set before the run changed.
DO $$
DECLARE bad int;
BEGIN
  SELECT count(*) INTO bad FROM public.sources s WHERE s.id::text = ANY (${ids(types)}) AND s.source_type IS NULL;
  IF bad <> 0 THEN RAISE EXCEPTION '0016-data-source-type: % planned source_type rows are still NULL', bad; END IF;
  SELECT count(*) INTO bad FROM public.sources s WHERE s.id::text = ANY (${ids(roles)}) AND s.source_role IS NULL;
  IF bad <> 0 THEN RAISE EXCEPTION '0016-data-source-type: % planned source_role rows are still NULL', bad; END IF;
  SELECT count(*) INTO bad FROM _sb_prior p JOIN public.sources s ON s.id = p.id
   WHERE (p.source_role IS NOT NULL AND s.source_role IS DISTINCT FROM p.source_role) OR (p.source_type IS NOT NULL AND s.source_type IS DISTINCT FROM p.source_type);
  IF bad <> 0 THEN RAISE EXCEPTION '0016-data-source-type: % classified row(s) were overwritten', bad; END IF;
  RAISE NOTICE '0016-data-source-type OK (${roles.length} source_role, ${types.length} source_type planned)';
END $$;

COMMIT;
`);
