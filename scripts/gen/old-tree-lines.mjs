// Generates scripts/ci/old-tree-lines.json: {path: lineCount} for every file under fsi-app/ at one commit of the old repo.
// Usage: node scripts/gen/old-tree-lines.mjs <old-repo-dir> [commit]. Git plumbing only; nothing is checked out.
// Paths drop the "fsi-app/" prefix (the form headers cite); counts are `wc -l` counts (newline characters).
import { spawn, execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const [repo, commit = "646fb098c"] = process.argv.slice(2);
if (!repo) {
  console.error("usage: node scripts/gen/old-tree-lines.mjs <old-repo-dir> [commit]");
  process.exit(2);
}
const full = execFileSync("git", ["-C", repo, "rev-parse", commit], { encoding: "utf8" }).trim();
const entries = execFileSync("git", ["-C", repo, "ls-tree", "-r", "-z", full, "--", "fsi-app"], { encoding: "utf8", maxBuffer: 1 << 28 })
  .split("\0").filter(Boolean).map((l) => ({ sha: l.split(/\s+/)[2], path: l.slice(l.indexOf("\t") + 1) }));

const child = spawn("git", ["-C", repo, "cat-file", "--batch"], { stdio: ["pipe", "pipe", "inherit"] });
const chunks = [];
child.stdout.on("data", (c) => chunks.push(c));
child.stdin.end(entries.map((e) => `${e.sha}\n`).join(""));
await new Promise((res) => child.on("close", res));
const buf = Buffer.concat(chunks);

const counts = {};
let pos = 0;
for (const e of entries) {
  const nl = buf.indexOf(10, pos);
  const [, , size] = buf.toString("latin1", pos, nl).split(" ");
  const start = nl + 1;
  const end = start + Number(size);
  let n = 0;
  for (let i = start; i < end; i++) if (buf[i] === 10) n++;
  counts[e.path.replace(/^fsi-app\//, "")] = n;
  pos = end + 1;
}
const sorted = Object.fromEntries(Object.entries(counts).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
const doc = {
  _comment: `Line counts of every file under fsi-app/ at old repo commit ${full} (prefix dropped). Counts are wc -l (newline-terminated lines). Generated by scripts/gen/old-tree-lines.mjs. Data, not code.`,
  commit: full,
  lines: sorted,
};
writeFileSync("scripts/ci/old-tree-lines.json", JSON.stringify(doc, null, 1) + "\n");
console.log(`${entries.length} files`);
