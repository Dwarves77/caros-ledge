// Generates supabase/migrations/0015_data_screen_verdicts.sql from the old repo's reviewed-verdicts.json (one entry per census id:
// verdict, reason, reviewer). The JSON is read, never copied into this tree. Usage:
//   node scripts/gen/screen-verdicts-sql.mjs <old_repo_root> > supabase/migrations/0015_data_screen_verdicts.sql
// An entry that is not a uuid key with a known verdict and a non-empty reason stops the run; nothing is invented or defaulted.
import { readFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) {
  console.error("usage: node scripts/gen/screen-verdicts-sql.mjs <old_repo_root>");
  process.exit(2);
}
const entries = JSON.parse(readFileSync(join(root, "fsi-app/scripts/mint/reviewed-verdicts.json"), "utf8"));
const VERDICTS = ["on_vertical", "off_vertical", "ambiguous"];
const q = (s) => `'${s.replace(/'/g, "''")}'`;
const rows = Object.keys(entries)
  .sort()
  .map((id) => {
    const e = entries[id];
    if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(id)) throw new Error(`not a uuid: ${id}`);
    if (!VERDICTS.includes(e.verdict)) throw new Error(`${id}: unknown verdict ${e.verdict}`);
    if (typeof e.reason !== "string" || !e.reason.trim()) throw new Error(`${id}: empty reason`);
    return `(${q(id)}, ${q(e.verdict)}, ${q(e.reason)}, ${typeof e.reviewer === "string" && e.reviewer ? q(e.reviewer) : "NULL"})`;
  });
const n = rows.length;
const by = Object.fromEntries(VERDICTS.map((v) => [v, Object.values(entries).filter((e) => e.verdict === v).length]));

process.stdout.write(`-- 0015 DATA migration: the ${n.toLocaleString("en-US")} reviewed screen verdicts into screen_verdicts (P2-S2, owed by register P1-05 mint.md section 8 and IMPROVEMENTS IMP-039).
--
-- GENERATED by scripts/gen/screen-verdicts-sql.mjs from the old repo's fsi-app/scripts/mint/reviewed-verdicts.json (${by.on_vertical} on_vertical,
-- ${by.off_vertical} off_vertical, ${by.ambiguous} ambiguous; the file's \`reason\` becomes \`basis\`). Do not edit by hand: regenerate.
--
-- THIS IS A DATA MIGRATION. TWO-TRACK POLICY: it ships with its consumer (src/features/mint/screen.ts loadReviewedVerdicts) and is
-- RUN ONLY AT THE CUTOVER WINDOW, by the operator's executor, after 0014 and after the census_worklist rows exist; the CI schema job
-- never runs it for real, it runs it inside a rolled-back transaction after the fixture named below (rule 15: the SQL is proven to execute).
--
-- Idempotent: INSERT ... ON CONFLICT (census_id) DO NOTHING; a second run, or a verdict ruled since, is never overwritten.
-- A census id that is absent from census_worklist is listed in a NOTICE and skipped, never invented.
-- Reversal: DELETE FROM public.screen_verdicts WHERE the row's reviewer and basis are those of this file and ruled_at >= the run time.

-- catalog: none (data migration, not run by the schema job)
-- rollback-test: scripts/ci/fixtures/data-0015-census.sql

BEGIN;

CREATE TEMP TABLE _sv_in (census_id uuid PRIMARY KEY, verdict text NOT NULL, basis text NOT NULL, reviewer text) ON COMMIT DROP;

INSERT INTO _sv_in (census_id, verdict, basis, reviewer) VALUES
${rows.join(",\n")};

CREATE TEMP TABLE _sv_prior ON COMMIT DROP AS
SELECT s.census_id, s.verdict, s.basis FROM public.screen_verdicts s WHERE s.census_id IN (SELECT census_id FROM _sv_in);

DO $$
DECLARE absent text; n_absent int;
BEGIN
  SELECT string_agg(i.census_id::text, ', ' ORDER BY i.census_id), count(*) INTO absent, n_absent
    FROM _sv_in i WHERE NOT EXISTS (SELECT 1 FROM public.census_worklist c WHERE c.id = i.census_id);
  IF n_absent > 0 THEN RAISE NOTICE '0015-data-screen-verdicts: % census id(s) absent from census_worklist, skipped: %', n_absent, absent; END IF;
END $$;

INSERT INTO public.screen_verdicts (census_id, verdict, basis, reviewer)
SELECT i.census_id, i.verdict, i.basis, i.reviewer FROM _sv_in i
 WHERE EXISTS (SELECT 1 FROM public.census_worklist c WHERE c.id = i.census_id)
ON CONFLICT (census_id) DO NOTHING;

-- Self-check 0015-data-screen-verdicts: every entry of the file is accounted for, either present in screen_verdicts or skipped as absent,
-- and no verdict that was ruled before the load changed.
DO $$
DECLARE n_file int; n_present int; n_absent int; n_changed int;
BEGIN
  SELECT count(*) INTO n_changed FROM _sv_prior p JOIN public.screen_verdicts s ON s.census_id = p.census_id
   WHERE s.verdict <> p.verdict OR s.basis <> p.basis;
  IF n_changed <> 0 THEN RAISE EXCEPTION '0015-data-screen-verdicts: % earlier verdict(s) were overwritten', n_changed; END IF;
  SELECT count(*) INTO n_file FROM _sv_in;
  IF n_file <> ${n} THEN RAISE EXCEPTION '0015-data-screen-verdicts: loaded % entries, the file has ${n}', n_file; END IF;
  SELECT count(*) INTO n_present FROM _sv_in i WHERE EXISTS (SELECT 1 FROM public.screen_verdicts s WHERE s.census_id = i.census_id);
  SELECT count(*) INTO n_absent FROM _sv_in i WHERE NOT EXISTS (SELECT 1 FROM public.census_worklist c WHERE c.id = i.census_id);
  IF n_present + n_absent <> n_file THEN
    RAISE EXCEPTION '0015-data-screen-verdicts: % present + % absent <> % entries', n_present, n_absent, n_file;
  END IF;
  RAISE NOTICE '0015-data-screen-verdicts OK (% of % entries present, % skipped as absent)', n_present, n_file, n_absent;
  -- The provenance mix at load (IMP-045): entries per reviewer, so the executor sees who ruled what.
  RAISE NOTICE '0015-data-screen-verdicts reviewers: %', (SELECT string_agg(coalesce(reviewer, '(none)') || '=' || n, ', ' ORDER BY coalesce(reviewer, '(none)')) FROM (SELECT reviewer, count(*) AS n FROM _sv_in GROUP BY reviewer) r);
END $$;

COMMIT;
`);
