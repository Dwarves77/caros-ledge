// Writes the rollback-test fixture and the assertions of migration 0108_data_claim_markers from scripts/ci/fixtures/claim-markers.json, the same cases tests/r2f/markers.test.ts runs through bindClaimMarkers: the JavaScript rule
// and the SQL rule are proven on one set of paragraphs. node scripts/gen/claim-marker-fixture.mjs ; tests/r2f/markers.test.ts fails when the committed files differ from what this writes.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const ITEM = "01080000-0000-4000-8000-0000000000a1";
const SECTION = "01080000-0000-4000-8000-0000000000b1";
const lit = (s) => `E'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "''").replace(/\n/g, "\\n")}'`;

/** The fixture text and the assertion text for a case file. */
export function renderClaimMarkerFixture(cases) {
  const claims = cases.claims.map((c) => `  ('${c.id}', '${ITEM}', ${lit(c.text)}, '${c.kind}')`).join(",\n");
  const md = cases.paragraphs.map((p, i) => p.md + (cases.separators[i] ?? "")).join("");
  const expected = cases.paragraphs.map((p, i) => p.expected + (cases.separators[i] ?? "")).join("");
  const c = cases.expectedCounts;
  const fixture = `-- GENERATED by scripts/gen/claim-marker-fixture.mjs from scripts/ci/fixtures/claim-markers.json: the rollback-test fixture of 0108_data_claim_markers.sql. DO NOT EDIT BY HAND.
-- One item with ${cases.claims.length} claims and one section of ${cases.paragraphs.length} paragraphs (nine cases: one claim states it, two claims with one text, no claim, a claim under 24 characters, an already marked paragraph, two claims in one paragraph, a slot line, an analysis claim, case).
INSERT INTO public.intelligence_items (id, title, domain) VALUES ('${ITEM}', 'fixture 0108', 1);
INSERT INTO public.section_claim_provenance (id, intelligence_item_id, claim_text, claim_kind) VALUES
${claims};
INSERT INTO public.intelligence_item_sections (id, item_id, section_key, section_order, content_md, is_conditional) VALUES ('${SECTION}', '${ITEM}', '1', 1, ${lit(md)}, false);
`;
  const assertions = `-- GENERATED by scripts/gen/claim-marker-fixture.mjs from scripts/ci/fixtures/claim-markers.json: the assertions about the FIXTURE of 0108_data_claim_markers.sql, run in the same rolled-back transaction after the file. DO NOT EDIT BY HAND.
-- The section comes out exactly as bindClaimMarkers (core/brief/claim-marker.ts) writes it, with its separators kept: ${c.marked} paragraphs newly marked, ${c.already} already marked, ${c.skipped} slot line skipped, ${c.unmarked} left unmarked.
DO $$
DECLARE got text;
BEGIN
  SELECT content_md INTO got FROM public.intelligence_item_sections WHERE id = '${SECTION}';
  IF got IS DISTINCT FROM ${lit(expected)} THEN RAISE EXCEPTION 'data-0108 assertions: the section is not what the rule writes: %', got; END IF;
  RAISE NOTICE 'data-0108 assertions OK';
END $$;
`;
  return { fixture, assertions };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { fixture, assertions } = renderClaimMarkerFixture(JSON.parse(readFileSync("scripts/ci/fixtures/claim-markers.json", "utf8")));
  writeFileSync("scripts/ci/fixtures/data-0108-markers.sql", fixture);
  writeFileSync("scripts/ci/fixtures/data-0108-markers.assert.sql", assertions);
  console.log("data-0108-markers fixture and assertions written");
}
