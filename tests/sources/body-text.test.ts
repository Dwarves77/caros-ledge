// R2c C7 and C9: capture correctness. INV-R2c-8 (the 3,060-character legal text classifies as content), one entity decoder that decodes once, the Federal Register fallback never stores a summary as the document, no archive is read,
// and a decompression bomb is refused.
import assert from "node:assert/strict";
import { gzipSync } from "node:zlib";
import { test } from "node:test";

import { fetchDocumentApi } from "@/core/fetch/api";
import { BODY_CLASS, classifyBody, isErrorBody, toText } from "@/core/fetch/classify-body";
import { capture } from "@/core/fetch/capture";
import { decodeEntities, stripTags } from "@/core/fetch/entities";
import { strip } from "@/features/sources/walkers/xml";
import { decodeXmlBody } from "@/features/sources/walkers/sitemap";

import { memoryDb } from "../_support/memory-db.ts";
import { instant, routed } from "../_support/net.ts";

const publicHost = async () => ["93.184.216.34"];
const open = () => memoryDb({ system_state: [{ id: true, scrape_cadence: "weekly", scrape_start_date: "2026-01-05", global_processing_paused: false }] }).db;

// A legal head the way a real instrument reads: long prose that happens to use the words the old error signatures matched.
const legalText = (() => {
  const sentence = "Where the service is unavailable or the operator is forbidden from reporting, the authority shall record that no entry was found and the matter is not found to be in breach. ";
  let s = "Article 1. Subject matter. ";
  while (s.length < 3060) s += sentence;
  return s.slice(0, 3060);
})();

test("INV-R2c-8: a 3,060-character legal text that says unavailable, forbidden and not found classifies as content", () => {
  assert.equal(legalText.length, 3060);
  assert.equal(isErrorBody(legalText), false);
  assert.equal(classifyBody(legalText).class, BODY_CLASS.OK);
  // The structure still catches the real thing: a short body with a signature, and a tiny body.
  assert.equal(isErrorBody("Access Denied. You do not have permission to access this server. Reference #18.1234 ".repeat(2)), true);
  assert.equal(isErrorBody("403 Forbidden"), true);
  assert.equal(classifyBody("The request could not be satisfied. Generated by cloudfront. ".repeat(6)).class, BODY_CLASS.CDN_BLOCK);
  // A long page that merely opens with a script-shell banner is a document, not a shell.
  assert.equal(classifyBody(`Please enable JavaScript for the best experience. ${legalText}`).class, BODY_CLASS.OK);
});
test("toText decodes a reference once: the text &amp;lt; stays &lt;, never <", () => {
  assert.equal(toText("<p>a &amp;lt;b&amp;gt; c</p>"), "a &lt;b&gt; c");
  assert.equal(decodeEntities("&amp;amp;"), "&amp;");
  assert.equal(strip("&amp;lt;b&amp;gt;"), "&lt;b&gt;", "the XML decoder is the same decoder");
});
test("toText survives every reference the register lists: named, numeric, invalid code points, comments and a > in an attribute", () => {
  assert.equal(toText("<p>caf&eacute; &ndash; it&rsquo;s &sect;5 &nbsp;&#169; &#xA9;</p>"), "café – it’s §5 © ©");
  assert.doesNotThrow(() => toText("&#x110000; &#99999999; &#0; &#xD800;"));
  assert.equal(toText("&#x110000;&#99999999;&#xD800;"), "���");
  assert.equal(decodeEntities("&#150;"), "–", "a C1 reference reads as windows-1252 as a browser does");
  assert.equal(decodeEntities("&nosuchentity; &amp"), "&nosuchentity; &amp", "an unknown name and a reference with no semicolon stay literal");
  assert.equal(toText("a<!-- hidden remark -->b"), "a b");
  assert.equal(toText("<a title=\"x>y\" href='z>w'>text</a>"), "text");
  assert.equal(toText("if a < b and c > d then <b>bold</b>"), "if a < b and c > d then bold");
  assert.equal(toText("<script>var x = '<p>';</script><style>p{}</style>kept"), "kept");
  assert.equal(stripTags("<!-- never closed"), " ");
});
test("the XML strip keeps a CDATA section literal and drops its markup", () => {
  assert.equal(strip("<title><![CDATA[AT&amp;T <b>news</b>]]></title>"), "AT&amp;T news");
  assert.equal(strip("<title>AT&amp;T &#38; Co</title>"), "AT&T & Co");
});

test("the Federal Register fallback stores the document text, never the title and abstract as status 200", async () => {
  const url = "https://www.federalregister.gov/documents/2023/05/01/2023-12345/some-rule";
  const net = routed(async (u) => (u.includes("/api/v1/documents/") ? new Response(JSON.stringify({ title: "Some rule", abstract: "A long abstract that is not the document. ".repeat(10), raw_text_url: "https://www.federalregister.gov/documents/full_text/text/2023/05/01/2023-12345.txt" }), { headers: { "content-type": "application/json" } }) : new Response("gone", { status: 404 })));
  const out = await fetchDocumentApi(url, { db: open(), env: {}, fetchImpl: net.fetch, sleep: instant, resolveHost: publicHost }, { max: 1_000_000 });
  assert.equal(out?.status, 0);
  assert.equal(out?.text, "");
  assert.equal(out?.refusal?.reason, "raw_text_unavailable");
  const good = routed(async (u) => (u.includes("/api/v1/documents/") ? new Response(JSON.stringify({ title: "Some rule", raw_text_url: "https://www.federalregister.gov/full.txt" }), { headers: { "content-type": "application/json" } }) : new Response(`<pre>${legalText}</pre>`, { headers: { "content-type": "text/plain" } })));
  const full = await fetchDocumentApi(url, { db: open(), env: {}, fetchImpl: good.fetch, sleep: instant, resolveHost: publicHost }, { max: 1_000_000 });
  assert.equal(full?.status, 200);
  assert.ok((full?.text.length ?? 0) > 2000);
});
test("a Wayback read is forbidden: a refused capture never asks an archive, and the hold carries no archive suffix", async () => {
  const net = routed(async () => new Response("Just a moment...", { status: 403 }));
  const res = await capture("https://agency.gov/p", { family: "generic" }, { db: open(), env: {}, fetchImpl: net.fetch, sleep: instant, resolveHost: publicHost });
  assert.equal(res.usable, false);
  assert.equal(res.holdReason, "capture_blocked");
  assert.ok(!net.calls.some((u) => /archive\.org/.test(u)), "no request went to an archive");
  assert.equal(net.calls.length, 1);
});
test("a robots refusal is a hold with its own reason and the rule, not a generic block", async () => {
  const net = routed(async () => new Response("never", { status: 200 }), { "agency.gov": { status: 200, body: "User-agent: *\nDisallow: /p\n" } });
  const res = await capture("https://agency.gov/p", { family: "generic" }, { db: open(), env: {}, fetchImpl: net.fetch, sleep: instant, resolveHost: publicHost });
  assert.equal(res.holdReason, "robots_disallowed");
  assert.equal(res.refusal?.rule, "Disallow: /p");
});

test("a gzipped sitemap that inflates past the bound is refused; a normal one is read (decompression bomb fixture)", async () => {
  const bomb = gzipSync(Buffer.alloc(20 * 1024 * 1024, 0x61));
  assert.ok(bomb.length < 100_000, "a small archive");
  await assert.rejects(() => decodeXmlBody(bomb, "https://agency.gov/sitemap.xml.gz", 1024 * 1024), /larger than|ERR_BUFFER_TOO_LARGE|maxOutputLength/i);
  const fine = gzipSync(Buffer.from("<urlset><url><loc>https://agency.gov/a</loc></url></urlset>"));
  assert.match(await decodeXmlBody(fine, "https://agency.gov/sitemap.xml.gz"), /<loc>/);
});
