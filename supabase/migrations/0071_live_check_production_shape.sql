--
-- The CI database is built to match scripts/ci/data/production-shape.json (read from production with the query below by scripts/cutover/read-production-shape.mjs). This function is that query, so the live check
-- (scripts/ci/live/checks.mjs, check `production-shape`) asks the deployed project the question the file was made from, and the schema job asks the CI database the same: the file, CI and production cannot disagree unseen.
-- It reads the catalog only and returns configuration (role names and attributes, ACL text), never data. Security definer so it sees pg_db_role_setting and information_schema for auth; executable by service_role only.
--
-- GENERATED by scripts/gen/shape-function-sql.mjs from scripts/ci/data/production-shape.sql. Do not edit by hand: migration-checks fails when this file differs from the generator.
--
-- Reversal: supabase/migrations/down/0071.sql.

-- catalog: function

BEGIN;

CREATE FUNCTION public.live_check_production_shape() RETURNS jsonb
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
    AS $shape$
SELECT jsonb_build_object(
  'databaseOwner', (SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname = current_database()),
  'roles', (SELECT coalesce(jsonb_agg(jsonb_build_object('name', rolname, 'super', rolsuper, 'inherit', rolinherit, 'createrole', rolcreaterole, 'createdb', rolcreatedb, 'login', rolcanlogin, 'replication', rolreplication, 'bypassrls', rolbypassrls, 'connlimit', rolconnlimit) ORDER BY rolname), '[]'::jsonb)
              FROM pg_roles WHERE rolname !~ '^(pg_|cli_login_|ci_bootstrap)'),
  'memberships', (SELECT coalesce(jsonb_agg(jsonb_build_object('role', r.rolname, 'member', m.rolname) ORDER BY r.rolname, m.rolname), '[]'::jsonb)
                    FROM pg_auth_members am JOIN pg_roles r ON r.oid = am.roleid JOIN pg_roles m ON m.oid = am.member
                   WHERE r.rolname !~ '^(pg_|cli_login_|ci_bootstrap)' AND m.rolname !~ '^(pg_|cli_login_|ci_bootstrap)'),
  'roleSettings', (SELECT coalesce(jsonb_agg(jsonb_build_object('role', coalesce(r.rolname, '*'), 'database', coalesce(d.datname, '*'), 'settings', ARRAY(SELECT replace(c, chr(92), '') FROM unnest(s.setconfig) c)) ORDER BY coalesce(r.rolname, '*'), coalesce(d.datname, '*')), '[]'::jsonb)
                     FROM pg_db_role_setting s LEFT JOIN pg_roles r ON r.oid = s.setrole LEFT JOIN pg_database d ON d.oid = s.setdatabase
                    WHERE coalesce(r.rolname, '') !~ '^(cli_login_|ci_bootstrap)' AND coalesce(d.datname, current_database()) = current_database()),
  'schemaAcls', (SELECT coalesce(jsonb_agg(jsonb_build_object('schema', nspname, 'owner', pg_get_userbyid(nspowner), 'acl', ARRAY(SELECT x::text FROM unnest(nspacl) x ORDER BY x::text COLLATE "C")) ORDER BY nspname), '[]'::jsonb)
                   FROM pg_namespace WHERE nspname !~ '^pg_' AND nspname <> 'information_schema'),
  'defaultAcls', (SELECT coalesce(jsonb_agg(jsonb_build_object('role', pg_get_userbyid(defaclrole), 'schema', CASE WHEN defaclnamespace = 0 THEN '*' ELSE defaclnamespace::regnamespace::text END, 'objtype', defaclobjtype::text, 'acl', ARRAY(SELECT x::text FROM unnest(defaclacl) x ORDER BY x::text COLLATE "C"))
                                            ORDER BY pg_get_userbyid(defaclrole), CASE WHEN defaclnamespace = 0 THEN '*' ELSE defaclnamespace::regnamespace::text END, defaclobjtype::text), '[]'::jsonb) FROM pg_default_acl),
  'authUsers', (SELECT coalesce(jsonb_agg(jsonb_build_object('column', column_name, 'type', data_type, 'nullable', is_nullable = 'YES') ORDER BY ordinal_position), '[]'::jsonb) FROM information_schema.columns WHERE table_schema = 'auth' AND table_name = 'users'),
  'authFunctions', (SELECT coalesce(jsonb_agg(jsonb_build_object('name', p.proname, 'definition', pg_get_functiondef(p.oid)) ORDER BY p.proname), '[]'::jsonb) FROM pg_proc p WHERE p.pronamespace = 'auth'::regnamespace AND p.proname IN ('uid', 'role', 'jwt', 'email')),
  'serverSettings', (SELECT coalesce(jsonb_object_agg(name, setting ORDER BY name), '{}'::jsonb) FROM pg_settings
                      WHERE name IN ('row_security', 'default_transaction_isolation', 'standard_conforming_strings'))
)
$shape$;
REVOKE ALL ON FUNCTION public.live_check_production_shape() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.live_check_production_shape() TO service_role;
COMMENT ON FUNCTION public.live_check_production_shape() IS 'The shape of the database (roles, role settings, ACLs, default privileges) as one jsonb document; compared with scripts/ci/data/production-shape.json by the live check and the schema job (R1b migration 0071).';

-- Self-check 0071-production-shape: only service_role may execute it (anon and authenticated are refused by the privilege, not by an error inside it); it answers every section the live check compares, the roles it lists include
-- service_role with BYPASSRLS (the attribute the old CI stub lacked), and the answer names the database owner.
DO $$
DECLARE doc jsonb;
BEGIN
  IF has_function_privilege('anon', 'public.live_check_production_shape()', 'EXECUTE') OR has_function_privilege('authenticated', 'public.live_check_production_shape()', 'EXECUTE') THEN
    RAISE EXCEPTION '0071-production-shape: a client role can execute it';
  END IF;
  IF NOT has_function_privilege('service_role', 'public.live_check_production_shape()', 'EXECUTE') THEN RAISE EXCEPTION '0071-production-shape: service_role cannot execute it'; END IF;
  BEGIN
    SET LOCAL ROLE authenticated;
    PERFORM public.live_check_production_shape();
    RESET ROLE;
    RAISE EXCEPTION '0071-production-shape: authenticated executed it';
  EXCEPTION WHEN SQLSTATE '42501' THEN RESET ROLE;
  END;
  doc := public.live_check_production_shape();
  IF NOT (doc ?& ARRAY['databaseOwner', 'roles', 'memberships', 'roleSettings', 'schemaAcls', 'defaultAcls', 'authUsers', 'authFunctions', 'serverSettings']) THEN
    RAISE EXCEPTION '0071-production-shape: the answer lacks a section: %', (SELECT string_agg(k, ',') FROM jsonb_object_keys(doc) k);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements(doc->'roles') r WHERE r->>'name' = 'service_role' AND (r->>'bypassrls')::boolean) THEN RAISE EXCEPTION '0071-production-shape: service_role is not listed with BYPASSRLS'; END IF;
  IF coalesce(doc->>'databaseOwner', '') = '' THEN RAISE EXCEPTION '0071-production-shape: no database owner'; END IF;
  RAISE NOTICE '0071-production-shape OK';
END $$;

COMMIT;
