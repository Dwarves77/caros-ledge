-- 0107 canonicalize_citation_url_keeps_case (R2f F6; register D:7/8 class, MASTER gap 8). The database canonicaliser of a citation URL is the mirror of the parse module's canonicalizeUrl.
--
-- canonicalize_citation_url lower-cased the WHOLE url, path and query included, so two citations that differ only in the case of a path ("/Law/Act-1" and "/law/act-1", two documents on case-sensitive servers) were one
-- citation to criterion 2 of validate_item_provenance and to capture_holding_quote, while the JavaScript canonicaliser (src/core/parse canonicalizeUrl, which every JavaScript caller uses through canonicalUrl) kept case. The function now
-- does what canonicalizeUrl does: scheme to https, userinfo and a leading www. dropped, host lower-cased, the default ports dropped, path and query CASE KEPT, trailing slashes dropped, the query decoded, tracking parameters removed,
-- sorted and re-encoded, the fragment dropped; a string that is not an absolute URL is returned trimmed of markers and trailing punctuation. Two helpers carry the form encoding. The text between the markers is generated by
-- renderCanonicalizeUrlSql() in src/core/parse/identifiers.ts (a test regenerates and diffs it; schema:local runs the function and canonicalizeUrl over one list of URLs and they agree).
-- Nothing stores a canonical form (no index, view or column default calls the function; the two callers compute both sides on every call), so no row changes.
-- Access: the function and its helpers read no table.
--
-- Reversal: down/0107.sql restores the previous body (lower-cased whole string) and drops the two helpers.

-- catalog: function

BEGIN;

-- BEGIN generated: src/core/parse/identifiers.ts renderCanonicalizeUrlSql(); do not edit by hand
CREATE OR REPLACE FUNCTION public.canonical_form_decode(s text) RETURNS text
    LANGUAGE sql IMMUTABLE STRICT
    SET search_path TO 'public', 'pg_temp'
    AS $$
  SELECT coalesce(convert_from(string_agg(CASE WHEN r.a[1] ~ '^%[0-9A-Fa-f]{2}$' THEN decode(substr(r.a[1], 2), 'hex') ELSE convert_to(replace(r.a[1], '+', ' '), 'UTF8') END, ''::bytea ORDER BY r.n), 'UTF8'), '')
    FROM regexp_matches(s, '%[0-9A-Fa-f]{2}|[^%]+|%', 'g') WITH ORDINALITY AS r(a, n)
$$;

CREATE OR REPLACE FUNCTION public.canonical_form_encode(s text) RETURNS text
    LANGUAGE sql IMMUTABLE STRICT
    SET search_path TO 'public', 'pg_temp'
    AS $$
  SELECT coalesce(string_agg(CASE WHEN c.ch ~ '^[A-Za-z0-9*._-]$' THEN c.ch WHEN c.ch = ' ' THEN '+' ELSE regexp_replace(upper(encode(convert_to(c.ch, 'UTF8'), 'hex')), '(..)', '%\1', 'g') END, '' ORDER BY c.n), '')
    FROM regexp_split_to_table(s, '') WITH ORDINALITY AS c(ch, n)
$$;

CREATE OR REPLACE FUNCTION public.canonicalize_citation_url(u text) RETURNS text
    LANGUAGE plpgsql IMMUTABLE STRICT
    SET search_path TO 'public', 'extensions', 'pg_temp'
    AS $$
DECLARE
  v_t text;
  m text[];
  v_host text;
  v_port text;
  v_path text;
  v_qs text;
BEGIN
  v_t := regexp_replace(regexp_replace(regexp_replace(u, '^\s+|\s+$', '', 'g'), '[*`]+$', ''), '[.,;:]+$', '');
  m := regexp_match(v_t, '^[A-Za-z][A-Za-z0-9+.-]*://([^/?#]*)([^?#]*)(?:\?([^#]*))?(?:#.*)?$');
  IF m IS NULL THEN RETURN v_t; END IF;
  v_host := lower(regexp_replace(m[1], '^.*@', ''));
  v_port := (regexp_match(v_host, ':(\d+)$'))[1];
  v_host := regexp_replace(regexp_replace(v_host, ':\d*$', ''), '^www\.', '');
  IF v_host = '' THEN RETURN v_t; END IF;
  IF v_port IS NOT NULL THEN v_port := (v_port::bigint)::text; IF v_port IN ('80', '443') THEN v_port := NULL; END IF; END IF;
  v_path := CASE WHEN length(m[2]) > 1 THEN regexp_replace(m[2], '/+$', '') ELSE '' END;
  IF m[3] IS NOT NULL THEN
    SELECT string_agg(public.canonical_form_encode(q.k) || '=' || public.canonical_form_encode(q.v), '&' ORDER BY q.k COLLATE "C", q.v COLLATE "C")
      INTO v_qs
      FROM (SELECT public.canonical_form_decode(split_part(p, '=', 1)) AS k, public.canonical_form_decode(CASE WHEN strpos(p, '=') = 0 THEN '' ELSE substr(p, strpos(p, '=') + 1) END) AS v
              FROM unnest(string_to_array(m[3], '&')) AS p WHERE p <> '') q
     WHERE lower(q.k) NOT IN ('utm_source', 'utm_medium', 'utm_campaign', 'utm_term', 'utm_content', 'utm_id', 'fbclid', 'gclid', 'msclkid', 'mc_cid', 'mc_eid');
  END IF;
  RETURN 'https://' || v_host || coalesce(':' || v_port, '') || v_path || CASE WHEN v_qs IS NULL OR v_qs = '' THEN '' ELSE '?' || v_qs END;
EXCEPTION WHEN character_not_in_repertoire OR invalid_text_representation OR numeric_value_out_of_range THEN
  RETURN v_t;
END;
$$;
-- END generated

COMMENT ON FUNCTION public.canonicalize_citation_url(text) IS 'The citation URL canonical form: the SQL mirror of canonicalizeUrl in src/core/parse (migration 0107). Path and query case are kept.';

-- Self-check 0107-canonical-url: case in the path and query is kept, the host is lower-cased, www., the default port, userinfo and the fragment are dropped, the scheme is https, the query is sorted without its tracking parameters, a trailing slash
-- is dropped, a marker or punctuation glued to the end is stripped, and a string that is not an absolute URL comes back trimmed.
DO $$
BEGIN
  IF public.canonicalize_citation_url('  HTTP://user:pw@WWW.Example.COM:443/Law/Act-1/?utm_source=x&B=2&a=%C3%A9+b&a=1#Frag ') IS DISTINCT FROM 'https://example.com/Law/Act-1?B=2&a=1&a=%C3%A9+b' THEN RAISE EXCEPTION '0107-canonical-url: wrong canonical form %', public.canonicalize_citation_url('  HTTP://user:pw@WWW.Example.COM:443/Law/Act-1/?utm_source=x&B=2&a=%C3%A9+b&a=1#Frag '); END IF;
  IF public.canonicalize_citation_url('https://example.com/Law') = public.canonicalize_citation_url('https://example.com/law') THEN RAISE EXCEPTION '0107-canonical-url: path case was folded'; END IF;
  IF public.canonicalize_citation_url('https://example.com:8443/x/**') IS DISTINCT FROM 'https://example.com:8443/x' THEN RAISE EXCEPTION '0107-canonical-url: port or marker handling wrong'; END IF;
  IF public.canonicalize_citation_url('Not A URL.,') IS DISTINCT FROM 'Not A URL' THEN RAISE EXCEPTION '0107-canonical-url: a non-URL was changed beyond its trim'; END IF;
  IF public.canonicalize_citation_url(NULL) IS NOT NULL THEN RAISE EXCEPTION '0107-canonical-url: null did not stay null'; END IF;
  RAISE NOTICE '0107-canonical-url OK';
END $$;

COMMIT;
